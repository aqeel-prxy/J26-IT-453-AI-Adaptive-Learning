"""
Pydantic Schemas for Learning Path Planning — Component 1 (Aqeel M.I.M)
AI-Based Goal-Aware and Prerequisite-Adaptive Mathematics Learning Path Planning for Grade 11 Students
"""
from uuid import UUID
from datetime import date
from typing import List, Dict, Any, Optional
from pydantic import BaseModel, Field


class RecommendedActivity(BaseModel):
    activity_type: str = Field(..., description="Action type: PROCEED_DIRECT, REVISE_PREREQUISITE, WORKED_EXAMPLE, PRACTICE, LESSON_UNIT")
    concept_id: Optional[str] = Field(None, description="UUID of target concept")
    concept_title: Optional[str] = Field(None, description="Title of target concept")
    rationale: str = Field(..., description="Educational justification generated by planning engine")
    estimated_duration_minutes: int = Field(15, description="Estimated time allocation")


class PathwayNode(BaseModel):
    concept_id: str
    code: Optional[str] = None
    title: Optional[str] = None
    order_index: Optional[int] = 1
    prerequisites: List[str] = []
    textbook_ref: Optional[str] = None
    status: str = Field(..., description="MASTERED, RECOMMENDED_NEXT, AVAILABLE, LOCKED, REVISION_REQUIRED")
    readiness_probability: float = Field(..., ge=0.0, le=1.0)
    confidence: Optional[float] = None
    model_version: Optional[str] = None
    is_terminal_objective: Optional[bool] = False


class PlanCreateRequest(BaseModel):
    student_id: UUID
    topic_category: str = "Indices and Logarithms"
    grade_level: Optional[int] = Field(11, description="Grade 10 or Grade 11")
    goal_type: str = Field("COMPREHENSIVE", description="TERM_TEST or COMPREHENSIVE")
    target_date: Optional[date] = None
    available_daily_minutes: int = Field(30, ge=10, le=180)


class PlanResponse(BaseModel):
    plan_id: str
    student_id: str
    topic_category: str
    grade_level: Optional[int] = 11
    goal_type: str
    target_date: Optional[str] = None
    available_daily_minutes: int
    current_concept_id: Optional[str] = None
    overall_readiness_score: Optional[float] = 0.5
    status: str
    recommended_activity: RecommendedActivity
    pathway_nodes: List[PathwayNode]


class DiagnosticResponseItem(BaseModel):
    question_id: str
    concept_id: str
    is_correct: bool
    response_time_ms: Optional[int] = 15000


class DiagnosticSubmitRequest(BaseModel):
    student_id: UUID
    topic_category: str = "Indices and Logarithms"
    grade_level: Optional[int] = 11
    goal_type: str = "COMPREHENSIVE"
    responses: List[DiagnosticResponseItem]


class DiagnosticSubmitResponse(BaseModel):
    plan_id: str
    student_id: str
    goal_type: str
    topic_category: str
    initial_readiness_vector: Dict[str, float]
    recommended_next_step: RecommendedActivity
    pathway_nodes: List[PathwayNode]


class ActivityCompleteRequest(BaseModel):
    student_id: UUID
    concept_id: str
    activity_type: str = "QUIZ"  # QUIZ, WORKED_EXAMPLE, PRACTICE, LESSON_UNIT
    is_successful: bool = True
    score: float = Field(1.0, ge=0.0, le=1.0)
    duration_seconds: int = Field(120, ge=1)


class ActivityCompleteResponse(BaseModel):
    status: str
    previous_concept_id: str
    next_concept_id: Optional[str] = None
    next_recommended_activity: RecommendedActivity
    pathway_nodes: List[PathwayNode]
